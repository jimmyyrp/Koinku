CREATE TABLE IF NOT EXISTS public.people (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(trim(name)) > 0),
  is_self boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS people_name_unique_idx
  ON public.people (lower(trim(name)));

ALTER TABLE public.transactions
  ADD COLUMN IF NOT EXISTS paid_by_id bigint REFERENCES public.people(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS transactions_paid_by_id_idx ON public.transactions (paid_by_id);

ALTER TABLE public.people ENABLE ROW LEVEL SECURITY;

