CREATE TABLE IF NOT EXISTS public.debts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_name text NOT NULL CHECK (length(trim(person_name)) > 0),
  amount numeric(14, 2) NOT NULL CHECK (amount > 0),
  direction text NOT NULL CHECK (direction IN ('borrow', 'repay')),
  note text NOT NULL DEFAULT '',
  debt_date date NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS debts_person_name_idx
  ON public.debts (lower(trim(person_name)));

CREATE INDEX IF NOT EXISTS debts_debt_date_idx
  ON public.debts (debt_date DESC);

ALTER TABLE public.debts ENABLE ROW LEVEL SECURITY;